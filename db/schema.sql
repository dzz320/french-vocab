-- 从外部（管理员 / service role）写库时的两个必须注意点
--
-- 1) owner_id 有默认值 auth.uid()，但外部连接里没有 JWT，auth.uid() 会是 null，
--    直接撞 not null 约束。所以绕过 RLS 的写库必须**显式带上 owner_id**。
--
-- 2) 用管理员身份写库时 RLS 不生效（bypass），写错 owner_id 不会报错但谁也看不见。
