-- ============================================================================
-- 法语生词本 · 云数据库结构
--
-- 6 张表，全部以 owner_id 做行级隔离：RLS 策略统一为 owner_id = auth.uid()，
-- 也就是说每个登录用户只看得到自己的数据（同一套表天然多租户）。
--
-- 这份脚本是**从线上库导出的结构**（information_schema + RLS 策略），
-- 用来在新的云环境里重建。字段名、类型、默认值、可空性都与线上一致。
--
-- 平台差异，执行前注意：
--   * auth.uid()：WorkBuddy 云服务 / Supabase 提供的内置函数，返回当前 JWT 的用户 id。
--     若目标库没有这个函数，先建一个（或改成自己的会话变量）：
--         create schema if not exists auth;
--         create or replace function auth.uid() returns text
--         language sql stable as $$ select current_setting('request.jwt.claim.sub', true) $$;
--   * gen_random_uuid() 未使用；这里不依赖任何扩展。
--   * id 的统一形态是「bigint 自增主键」；若平台建表工具给的是 serial，二者等价。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 词汇 / 词库
-- ---------------------------------------------------------------------------

-- 用户自建的生词库（如 B1 库、工程师库），与教材完全独立
create table if not exists fr_libraries (
  id          bigint generated by default as identity primary key,
  owner_id    text        not null default auth.uid(),
  name        text        not null,
  level       text        not null default '',
  description text        not null default '',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- 用户生词表，内联间隔重复（SRS）状态
create table if not exists fr_words (
  id          bigint generated by default as identity primary key,
  owner_id    text        not null default auth.uid(),
  book_id     bigint      null,          -- 来源教材（与词库二选一，可为空）
  unit_id     bigint      null,          -- 来源单元
  library_id  bigint      null,          -- 归属词库（null = 未分组）
  word        text        not null,
  phonetic    text        null,
  pos         text        null,
  meaning_zh  text        null,
  example_fr  text        null,
  example_zh  text        null,
  mnemonic    text        null,
  stage       integer     not null default 0,          -- SRS 阶段 0..5
  due_date    date        null,                        -- 下次复习日
  lapses      integer     not null default 0,           -- 遗忘次数
  status      text        not null default 'learning',  -- learning | mastered
  source      text        not null default 'manual',    -- manual | book | import | ai
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 教材
-- ---------------------------------------------------------------------------

-- 用户上传 / 创建的法语教材
create table if not exists fr_books (
  id          bigint generated by default as identity primary key,
  owner_id    text        not null default auth.uid(),
  title       text        not null,
  level       text        not null default 'A1',
  source_type text        not null default 'text',   -- text | pdf | docx
  source_path text        null,                      -- 云存储里的对象路径
  status      text        not null default 'draft',  -- draft | ready
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- 教材内的单元，排期依据 seq
create table if not exists fr_units (
  id         bigint generated by default as identity primary key,
  owner_id   text        not null default auth.uid(),
  book_id    bigint      not null,
  seq        integer     not null,
  title      text        not null,
  summary    text        null,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 学习记录与日程
-- ---------------------------------------------------------------------------

-- 学习日志（追加式），统计与连续天数的唯一事实来源
create table if not exists fr_study_logs (
  id          bigint generated by default as identity primary key,
  owner_id    text        not null default auth.uid(),
  word_id     bigint      not null,
  kind        text        not null,   -- new | review
  result      text        not null,   -- know | fuzzy | forgot
  reviewed_on date        not null,
  created_at  timestamptz not null default now()
);

-- 学习日程参数（日程为即时投影，不落逐日映射）
create table if not exists fr_study_plans (
  id               bigint generated by default as identity primary key,
  owner_id         text        not null default auth.uid(),
  book_id          bigint      null,
  daily_new        integer     not null default 10,
  daily_review_cap integer     not null default 50,
  weekly_days      jsonb       not null default '[1, 2, 3, 4, 5]',  -- 1=周一
  level            text        not null default 'A1',
  is_active        boolean     not null default true,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 行级隔离：每张表一条「只能看自己的行」策略
-- 六个策略完全一样，只是表名不同。
-- ---------------------------------------------------------------------------

alter table fr_libraries   enable row level security;
alter table fr_words       enable row level security;
alter table fr_books       enable row level security;
alter table fr_units       enable row level security;
alter table fr_study_logs  enable row level security;
alter table fr_study_plans enable row level security;

create policy fr_libraries_owner   on fr_libraries   for all using (owner_id = auth.uid()) with check (owner_id = auth.uid());
create policy fr_words_owner       on fr_words       for all using (owner_id = auth.uid()) with check (owner_id = auth.uid());
create policy fr_books_owner       on fr_books       for all using (owner_id = auth.uid()) with check (owner_id = auth.uid());
create policy fr_units_owner       on fr_units       for all using (owner_id = auth.uid()) with check (owner_id = auth.uid());
create policy fr_study_logs_owner  on fr_study_logs  for all using (owner_id = auth.uid()) with check (owner_id = auth.uid());
create policy fr_study_plans_owner on fr_study_plans for all using (owner_id = auth.uid()) with check (owner_id = auth.uid());

-- ---------------------------------------------------------------------------
-- 下面的索引**不是**线上导出的（线上没有单独保留索引定义），
-- 是按查询形态建议补的，加了只影响性能、不影响行为。
-- ---------------------------------------------------------------------------

create index if not exists fr_words_owner_due_idx     on fr_words (owner_id, due_date);
create index if not exists fr_words_owner_library_idx on fr_words (owner_id, library_id);
create index if not exists fr_words_owner_word_idx    on fr_words (owner_id, lower(word));   -- 例句点词按词形查
create index if not exists fr_units_book_seq_idx      on fr_units (book_id, seq);
create index if not exists fr_study_logs_owner_day_idx on fr_study_logs (owner_id, reviewed_on);
create index if not exists fr_libraries_owner_idx     on fr_libraries (owner_id);


